/**
 * Step 6's experiment layer (E01, E04): observations made by calling「收益测量」's
 * scripts in `scripts/experiment/step6/` (imported, never edited). No model call.
 *
 *   sets     (E01) both families' cases generated from the plan's seeds here and again in a
 *            fresh OS process; every file, material and message hashed; `checkSets` over all cases
 *   report   (E04) a scripted raw record built from the case plan (every holdout case ×
 *            base / parent / child × 3 repeats, costs of every kind): the report built twice
 *            in this process and once by `report.mjs` as its own OS process; what the report
 *            says recomputed from the record; the record changed in one run and in one cost
 *
 *   pilot    (E04, ADR 0011) the pilot's report over the scripted pilot's own raw.json (the
 *            E02 / E03 rehearsal's output): reproducible, and its added columns (component
 *            classes, instance-literal rate, follow-ups, repeat spread, the reliability
 *            criteria) recomputed from the records
 *
 * E04's records are scripted, not a real experiment's: they show the generators' own
 * reproducibility and traceability; the real records are R06's.
 */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const sha256 = text => createHash('sha256').update(text).digest('hex')

/** The experiment modules (W6) from `dir`. */
export async function loadExperiment(dir) {
  const url = name => pathToFileURL(join(dir, name)).href
  return { cases: await import(url('cases.mjs')), report: await import(url('report.mjs')), reportScript: join(dir, 'report.mjs'), dir }
}

/** Every generated byte of a case, hashed (files, materials, message, fingerprints). */
export function caseHashes(task) {
  const out = { message: sha256(task.message) }
  for (const [path, text] of Object.entries(task.files ?? {})) out[`files/${path}`] = sha256(text)
  for (const material of task.materials ?? []) out[`materials/${material.name}`] = sha256(material.content)
  out.fingerprints = sha256(JSON.stringify(task.fingerprints ?? []))
  return out
}

const generated = cases => cases.allCases().map(task => ({ id: task.id, family: task.family, set: task.set, seed: String(task.seed), hashes: caseHashes(task) }))

/** The same generation in a fresh OS process (so nothing this process holds can make two runs agree). */
function generateInChild(dir) {
  const code = `import { caseHashes } from ${JSON.stringify(import.meta.url)}
const cases = await import(${JSON.stringify(pathToFileURL(join(dir, 'cases.mjs')).href)})
process.stdout.write(JSON.stringify(cases.allCases().map(task => ({ id: task.id, family: task.family, set: task.set, seed: String(task.seed), hashes: caseHashes(task) }))))`
  const child = spawnSync(process.execPath, ['--input-type=module', '-e', code], { encoding: 'utf8', timeout: 120_000, maxBuffer: 64 * 1024 * 1024 })
  if (child.status !== 0) throw new Error(`case generation in a child process exited ${child.status}: ${child.stderr?.slice(0, 400)}`)
  return JSON.parse(child.stdout)
}

/** E01 observations: one generation here, one in a fresh process. */
export function setsObservation(experiment) {
  const first = generated(experiment.cases)
  const second = generateInChild(experiment.dir)
  const sets = {}
  for (const task of first) (sets[task.family] ??= {}), (sets[task.family][task.set] ??= []).push(task.id)
  return {
    families: [...experiment.cases.FAMILIES],
    sizes: { ...experiment.cases.SET_SIZES },
    first,
    second,
    sets,
    problems: experiment.cases.checkSets(experiment.cases.allCases()),
  }
}

/**
 * A scripted raw record over the case plan: every holdout case × 3 arms × 3 repeats,
 * passes by a fixed pattern (child best), one unknown result, costs of every kind.
 */
export function scriptedRecord(experiment) {
  const holdout = experiment.cases.allCases().filter(task => task.set === 'holdout')
  const passOf = { base: [false, false, true], parent: [false, true, true], child: [true, true, true] }
  const runs = []
  for (const task of holdout) {
    for (const arm of ['base', 'parent', 'child']) {
      for (let repeat = 1; repeat <= 3; repeat += 1) {
        const runId = `${task.id}#${arm}#${repeat}`
        const unknown = task.id === holdout[0].id && arm === 'base' && repeat === 3
        runs.push({ runId, family: task.family, caseId: task.id, arm, repeat, pass: unknown ? null : passOf[arm][repeat - 1], costUsd: Math.round((0.05 + 0.01 * repeat + (arm === 'child' ? 0.004 : 0)) * 1e6) / 1e6, componentsUsed: arm === 'base' ? [] : ['region-table-convention'] })
      }
    }
  }
  const costs = []
  for (const family of experiment.cases.FAMILIES) {
    for (const [kind, usd] of [['history', 0.2], ['dev', 0.11], ['improvement', 0.43], ['meta', 0.17], ['comparison', 0.61]]) costs.push({ kind, family, usd, ref: `scripted/${family}/${kind}` })
  }
  return {
    manifest: { experimentId: 'accept-step6-scripted', epochId: 'e'.repeat(64), model: 'scripted', thinking: 'on', improvers: { parent: 'v0', child: 'a'.repeat(64) }, decisions: { code: 'adopt (gate-passed)', tables: 'reject (no-improvement)' } },
    runs,
    costs,
    disagreements: [{ family: 'tables', ref: 'scripted/tables/dev', note: 'feedback check solved, hidden judge failed' }],
    notes: ['scripted record (accept-step6 E04), not a real experiment'],
  }
}

/** E04 observations. */
export async function reportObservation(experiment, work, { iterations } = {}) {
  await mkdir(work, { recursive: true })
  const raw = scriptedRecord(experiment)
  const options = iterations === undefined ? {} : { iterations }
  const first = experiment.report.buildReport(raw, options)
  const second = experiment.report.buildReport(structuredClone(raw), options)
  const records = join(work, 'raw.json')
  const out = join(work, 'report.md')
  await writeFile(records, `${JSON.stringify(raw, null, 2)}\n`)
  const cli = spawnSync(process.execPath, [experiment.reportScript, '--records', records, '--out', out, ...(iterations === undefined ? [] : ['--iterations', String(iterations)])], { encoding: 'utf8', timeout: 300_000 })
  const fromCli = await readFile(out, 'utf8').catch(() => undefined)
  // Change the record in one run and in one cost: the report must follow.
  const flipped = structuredClone(raw)
  const flipAt = flipped.runs.findIndex(run => run.arm === 'child' && run.pass === true)
  flipped.runs[flipAt].pass = false
  const costed = structuredClone(raw)
  costed.costs[0].usd += 1
  return {
    raw,
    first,
    second,
    cli: { code: cli.status, stderr: cli.stderr?.slice(0, 400), sameAsInProcess: fromCli === first },
    flipped: { runId: flipped.runs[flipAt].runId, report: experiment.report.buildReport(flipped, options) },
    costed: { ref: costed.costs[0].ref, report: experiment.report.buildReport(costed, options) },
  }
}

/**
 * E04, the pilot's report (ADR 0011): the pilot's raw records as `pilot/run.mjs --scripted`
 * wrote them (the rehearsal's `raw.json`), built twice here and once by `pilot/report.mjs` as
 * its own OS process; and the same records changed in one follow-up, one component class, one
 * run's rate and the judges' sample count, each built again. A scripted pilot, not the real one.
 * @param {string} dir the experiment directory (`scripts/experiment/step6`)
 * @param {string} records the pilot's `raw.json`
 * @param {string} work a scratch directory (created)
 */
export async function pilotReportObservation(dir, records, work) {
  await mkdir(work, { recursive: true })
  const reportScript = join(dir, 'pilot', 'report.mjs')
  const { buildPilotReport } = await import(pathToFileURL(reportScript).href)
  const raw = JSON.parse(await readFile(records, 'utf8'))
  const first = buildPilotReport(raw)
  const second = buildPilotReport(structuredClone(raw))
  const out = join(work, 'pilot-report.md')
  const cli = spawnSync(process.execPath, [reportScript, '--records', records, '--out', out], { encoding: 'utf8', timeout: 300_000 })
  const fromCli = await readFile(out, 'utf8').catch(() => undefined)
  const changed = mutate => {
    const copy = structuredClone(raw)
    const what = mutate(copy)
    return { what, report: what === undefined ? undefined : buildPilotReport(copy) }
  }
  return {
    raw,
    first,
    second,
    cli: { code: cli.status, stderr: cli.stderr?.slice(0, 400), sameAsInProcess: fromCli === first },
    changes: {
      followUp: changed(copy => {
        const run = copy.runs[0]
        if (run === undefined) return undefined
        run.followUp = run.followUp !== true
        return run.runId
      }),
      componentClass: changed(copy => {
        for (const [family, arms] of Object.entries(copy.components ?? {})) {
          for (const [arm, c] of Object.entries(arms ?? {})) {
            const x = c?.components?.[0]
            if (x === undefined) continue
            x.class = x.class === 'way-of-working' ? 'convention-or-fact' : 'way-of-working'
            return `${family} ${arm} ${x.kind}:${x.name}`
          }
        }
        return undefined
      }),
      rate: changed(copy => {
        const run = copy.runs.find(r => typeof r.rate === 'number')
        if (run === undefined) return undefined
        run.rate = run.rate >= 0.5 ? run.rate - 0.25 : run.rate + 0.25
        return run.runId
      }),
      judges: changed(copy => {
        copy.judges.samples += 1
        return 'judges.samples'
      }),
    },
  }
}
